package idudb

import (
	"errors"
	"io/fs"
	"path/filepath"
)

// DatabaseSize returns the total size of the files in the database directory
// dir. The database is excluded from analyses, see
// iduconfig.Settings.ExcludeFunc, so its size is measured separately, after
// the database has been closed. Files that are removed while it is being
// measured are ignored.
func DatabaseSize(dir string) (int64, error) {
	var total int64
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) && path != dir {
				return nil
			}
			return err
		}
		if d.IsDir() {
			return nil
		}
		info, err := d.Info()
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			return err
		}
		if info.Mode().IsRegular() {
			total += info.Size()
		}
		return nil
	})
	return total, err
}
